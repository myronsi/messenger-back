ALTER TABLE attachments DROP CONSTRAINT attachments_purpose_check;
ALTER TABLE attachments ADD CONSTRAINT attachments_purpose_check CHECK (purpose IN ('message', 'avatar', 'sticker'));

CREATE TABLE sticker_packs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    builtin_key TEXT UNIQUE,
    title       TEXT        NOT NULL CHECK (char_length(title) BETWEEN 1 AND 64),
    is_default  BOOLEAN     NOT NULL DEFAULT false,
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX sticker_packs_owner_idx ON sticker_packs (owner_id);

CREATE TABLE stickers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id       BIGINT      NOT NULL REFERENCES sticker_packs (id) ON DELETE CASCADE,
    attachment_id UUID        NOT NULL REFERENCES attachments (id) ON DELETE RESTRICT,
    builtin_key   TEXT,
    emoji         TEXT        NOT NULL CHECK (char_length(emoji) BETWEEN 1 AND 32),
    position      INTEGER     NOT NULL CHECK (position >= 0),
    is_animated   BOOLEAN     NOT NULL DEFAULT false,
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (pack_id, builtin_key)
);

CREATE INDEX stickers_pack_idx ON stickers (pack_id, position);
CREATE INDEX stickers_attachment_idx ON stickers (attachment_id);

CREATE TABLE user_sticker_packs (
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    pack_id    BIGINT      NOT NULL REFERENCES sticker_packs (id) ON DELETE CASCADE,
    installed  BOOLEAN     NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, pack_id)
);

CREATE INDEX user_sticker_packs_pack_idx ON user_sticker_packs (pack_id);

CREATE TABLE user_recent_stickers (
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    sticker_id BIGINT      NOT NULL REFERENCES stickers (id) ON DELETE CASCADE,
    used_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, sticker_id)
);

CREATE INDEX user_recent_stickers_sticker_idx ON user_recent_stickers (sticker_id);
CREATE INDEX user_recent_stickers_used_idx ON user_recent_stickers (user_id, used_at DESC);
