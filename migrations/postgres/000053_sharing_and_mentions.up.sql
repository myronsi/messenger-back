CREATE TABLE public_names (
    lower_name TEXT   PRIMARY KEY CHECK (lower_name ~ '^[a-z0-9_]{3,32}$'),
    user_id    BIGINT UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    chat_id    BIGINT UNIQUE REFERENCES chats (id) ON DELETE CASCADE,
    CONSTRAINT public_names_one_owner CHECK ((user_id IS NULL) <> (chat_id IS NULL))
);

INSERT INTO public_names (lower_name, user_id) SELECT LOWER(username), id FROM users;

CREATE FUNCTION users_sync_public_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public_names (lower_name, user_id) VALUES (LOWER(NEW.username), NEW.id);
    ELSIF LOWER(NEW.username) IS DISTINCT FROM LOWER(OLD.username) THEN
        UPDATE public_names SET lower_name = LOWER(NEW.username) WHERE user_id = NEW.id;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER users_sync_public_name AFTER INSERT OR UPDATE OF username ON users
    FOR EACH ROW EXECUTE FUNCTION users_sync_public_name();

ALTER TABLE chats ADD COLUMN public_name TEXT
    CONSTRAINT chats_public_name_format CHECK (public_name IS NULL OR (type = 'group' AND public_name ~ '^[A-Za-z0-9_]{3,32}$'));

CREATE FUNCTION chats_sync_public_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.public_name IS NOT DISTINCT FROM OLD.public_name THEN
        RETURN NEW;
    END IF;
    IF OLD.public_name IS NOT NULL THEN
        DELETE FROM public_names WHERE chat_id = NEW.id;
    END IF;
    IF NEW.public_name IS NOT NULL THEN
        INSERT INTO public_names (lower_name, chat_id) VALUES (LOWER(NEW.public_name), NEW.id);
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER chats_sync_public_name AFTER UPDATE OF public_name ON chats
    FOR EACH ROW EXECUTE FUNCTION chats_sync_public_name();

CREATE INDEX chats_public_name_search_idx ON chats (LOWER(public_name) text_pattern_ops) WHERE public_name IS NOT NULL;

CREATE TABLE chat_invite_links (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id    BIGINT      NOT NULL REFERENCES chats (id) ON DELETE CASCADE,
    token      TEXT        NOT NULL UNIQUE CHECK (token ~ '^[A-Za-z0-9]{22}$'),
    name       TEXT        CHECK (name IS NULL OR char_length(name) BETWEEN 1 AND 64),
    created_by BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    max_uses   INTEGER     CHECK (max_uses IS NULL OR max_uses BETWEEN 1 AND 100000),
    use_count  INTEGER     NOT NULL DEFAULT 0 CHECK (use_count >= 0),
    revoked_at TIMESTAMPTZ
);

CREATE INDEX chat_invite_links_chat_idx ON chat_invite_links (chat_id, id DESC);
CREATE INDEX chat_invite_links_created_by_idx ON chat_invite_links (created_by);

CREATE TABLE chat_bans (
    chat_id    BIGINT      NOT NULL REFERENCES chats (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    banned_by  BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (chat_id, user_id)
);

CREATE INDEX chat_bans_list_idx ON chat_bans (chat_id, created_at DESC, user_id DESC);
CREATE INDEX chat_bans_user_idx ON chat_bans (user_id);
CREATE INDEX chat_bans_banned_by_idx ON chat_bans (banned_by);

CREATE TABLE unread_mentions (
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    chat_id    BIGINT NOT NULL REFERENCES chats (id) ON DELETE CASCADE,
    message_id BIGINT NOT NULL CHECK (message_id > 0),
    PRIMARY KEY (user_id, chat_id, message_id)
);

CREATE INDEX unread_mentions_message_idx ON unread_mentions (chat_id, message_id);

CREATE FUNCTION participants_clear_mentions() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM unread_mentions WHERE user_id = OLD.user_id AND chat_id = OLD.chat_id;
        RETURN OLD;
    END IF;
    IF NEW.last_read_message_id IS NOT NULL
        AND NEW.last_read_message_id IS DISTINCT FROM OLD.last_read_message_id THEN
        DELETE FROM unread_mentions
        WHERE user_id = NEW.user_id AND chat_id = NEW.chat_id AND message_id <= NEW.last_read_message_id;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER participants_clear_mentions AFTER DELETE OR UPDATE OF last_read_message_id ON participants
    FOR EACH ROW EXECUTE FUNCTION participants_clear_mentions();

