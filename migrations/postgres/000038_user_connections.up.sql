CREATE TABLE user_connections (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider     TEXT        NOT NULL CHECK (provider IN ('github', 'spotify', 'steam', 'xbox', 'discord', 'twitch', 'youtube',
        'reddit', 'roblox', 'tiktok', 'bluesky', 'mastodon', 'website')),
    external_id  TEXT        NOT NULL CHECK (char_length(external_id) BETWEEN 1 AND 300),
    display_name TEXT        NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 100),
    profile_url  TEXT        CHECK (char_length(profile_url) BETWEEN 9 AND 500 AND profile_url LIKE 'https://%'),
    position     INT         NOT NULL,
    verified_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT user_connections_account_key UNIQUE (user_id, provider, external_id)
);

CREATE INDEX user_connections_user_position_idx ON user_connections (user_id, position);
