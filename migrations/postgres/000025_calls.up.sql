ALTER TABLE user_privacy_settings ADD COLUMN calls_enabled BOOLEAN NOT NULL DEFAULT true;

CREATE TABLE calls (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id           BIGINT REFERENCES chats (id) ON DELETE SET NULL,
    kind              TEXT        NOT NULL CHECK (kind IN ('direct', 'group')),
    initiator_id      BIGINT      NOT NULL,
    state             TEXT        NOT NULL CHECK (state IN ('ringing', 'active', 'ended')),
    end_reason        TEXT CHECK (end_reason IN ('completed', 'missed', 'declined', 'cancelled', 'failed')),
    epoch             BIGINT      NOT NULL DEFAULT 0 CHECK (epoch >= 0),
    version           BIGINT      NOT NULL DEFAULT 1 CHECK (version >= 1),
    max_participants  INTEGER     NOT NULL CHECK (max_participants >= 2),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at        TIMESTAMPTZ,
    ended_at          TIMESTAMPTZ,
    ring_expires_at   TIMESTAMPTZ NOT NULL,
    empty_since       TIMESTAMPTZ,
    summary_message_id BIGINT,
    summary_claimed_at TIMESTAMPTZ,
    summary_posted_at TIMESTAMPTZ,
    room_deleted_at   TIMESTAMPTZ,
    CONSTRAINT calls_end_shape CHECK ((state = 'ended') = (ended_at IS NOT NULL AND end_reason IS NOT NULL))
);

CREATE INDEX calls_chat_idx ON calls (chat_id);
CREATE UNIQUE INDEX calls_one_open_per_chat ON calls (chat_id) WHERE state <> 'ended';
CREATE INDEX calls_open_idx ON calls (created_at) WHERE state <> 'ended';
CREATE INDEX calls_ended_idx ON calls (ended_at) WHERE state = 'ended';

CREATE TABLE call_participants (
    call_id         BIGINT      NOT NULL REFERENCES calls (id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL,
    position        INTEGER     NOT NULL CHECK (position >= 0),
    state           TEXT        NOT NULL CHECK (state IN ('ringing', 'joined', 'declined', 'missed', 'left')),
    session_id      UUID,
    identity_key    TEXT,
    joined_at       TIMESTAMPTZ,
    left_at         TIMESTAMPTZ,
    disconnected_at TIMESTAMPTZ,
    PRIMARY KEY (call_id, user_id),
    CONSTRAINT call_participants_joined_shape CHECK ((state = 'joined') = (session_id IS NOT NULL AND identity_key IS NOT NULL AND joined_at IS NOT NULL))
);

CREATE UNIQUE INDEX call_participants_one_joined ON call_participants (user_id) WHERE state = 'joined';
CREATE INDEX call_participants_session_idx ON call_participants (session_id) WHERE state = 'joined';
CREATE INDEX call_participants_user_idx ON call_participants (user_id, call_id);

CREATE TABLE call_identities (
    session_id UUID        PRIMARY KEY REFERENCES user_sessions (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    public_key TEXT        NOT NULL CHECK (char_length(public_key) = 87),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX call_identities_user_idx ON call_identities (user_id);

CREATE TABLE call_key_envelopes (
    call_id              BIGINT      NOT NULL REFERENCES calls (id) ON DELETE CASCADE,
    epoch                BIGINT      NOT NULL CHECK (epoch >= 0),
    recipient_session_id UUID        NOT NULL,
    sender_session_id    UUID        NOT NULL,
    sender_user_id       BIGINT      NOT NULL,
    enc                  TEXT        NOT NULL CHECK (char_length(enc) BETWEEN 1 AND 128),
    ciphertext           TEXT        NOT NULL CHECK (char_length(ciphertext) BETWEEN 1 AND 256),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (call_id, epoch, recipient_session_id, sender_session_id)
);

CREATE TABLE call_start_requests (
    user_id           BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    client_request_id UUID        NOT NULL,
    call_id           BIGINT      NOT NULL REFERENCES calls (id) ON DELETE CASCADE,
    created           BOOLEAN     NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, client_request_id)
);

CREATE INDEX call_start_requests_call_idx ON call_start_requests (call_id);
CREATE INDEX call_start_requests_created_idx ON call_start_requests (created_at);
