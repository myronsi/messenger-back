ALTER TABLE attachments
    ADD COLUMN variants         JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(variants) = 'object'),
    ADD COLUMN placeholder      TEXT CHECK (char_length(placeholder) BETWEEN 1 AND 64),
    ADD COLUMN processing_state TEXT CHECK (processing_state IN ('queued', 'running', 'done', 'failed')),
    ADD COLUMN audio_title      TEXT CHECK (char_length(audio_title) BETWEEN 1 AND 100),
    ADD COLUMN audio_artist     TEXT CHECK (char_length(audio_artist) BETWEEN 1 AND 100),
    ADD COLUMN audio_album      TEXT CHECK (char_length(audio_album) BETWEEN 1 AND 100);

CREATE TABLE media_jobs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attachment_id UUID        NOT NULL REFERENCES attachments (id) ON DELETE CASCADE,
    kind          TEXT        NOT NULL CHECK (kind IN ('video', 'gif', 'audio', 'faststart')),
    state         TEXT        NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'running', 'done', 'failed')),
    attempts      INTEGER     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    error         TEXT CHECK (char_length(error) <= 500),
    run_after     TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at    TIMESTAMPTZ,
    finished_at   TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (attachment_id, kind)
);

CREATE INDEX media_jobs_queue_idx ON media_jobs (run_after, id) WHERE state = 'queued';
CREATE INDEX media_jobs_running_idx ON media_jobs (started_at) WHERE state = 'running';

CREATE TABLE upload_sessions (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    uploader_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose     TEXT        NOT NULL,
    kind        TEXT        NOT NULL DEFAULT '',
    filename    TEXT        NOT NULL CHECK (char_length(filename) BETWEEN 1 AND 255),
    size        BIGINT      NOT NULL CHECK (size > 0),
    chunk_size  INTEGER     NOT NULL CHECK (chunk_size > 0),
    received    BIGINT      NOT NULL DEFAULT 0 CHECK (received >= 0 AND received <= size),
    chunks      INTEGER     NOT NULL DEFAULT 0 CHECK (chunks >= 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX upload_sessions_uploader_idx ON upload_sessions (uploader_id);
CREATE INDEX upload_sessions_updated_idx ON upload_sessions (updated_at);
