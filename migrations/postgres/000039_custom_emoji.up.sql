ALTER TABLE attachments DROP CONSTRAINT attachments_purpose_check;
ALTER TABLE attachments ADD CONSTRAINT attachments_purpose_check
    CHECK (purpose IN ('message', 'avatar', 'sticker', 'profile_music', 'profile_background', 'emoji'));

CREATE TABLE emoji_packs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    chat_id    BIGINT UNIQUE REFERENCES chats (id) ON DELETE CASCADE,
    title      TEXT        NOT NULL CHECK (char_length(title) BETWEEN 1 AND 64),
    slug       TEXT UNIQUE CHECK (slug ~ '^[A-Za-z0-9]{8,32}$'),
    version    BIGINT      NOT NULL DEFAULT 0,
    hidden_at  TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT emoji_packs_kind CHECK ((chat_id IS NULL) = (slug IS NOT NULL))
);

CREATE INDEX emoji_packs_owner_idx ON emoji_packs (owner_id);

CREATE TABLE custom_emoji (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id       BIGINT      NOT NULL REFERENCES emoji_packs (id) ON DELETE CASCADE,
    attachment_id UUID        NOT NULL REFERENCES attachments (id) ON DELETE RESTRICT,
    shortcode     TEXT        NOT NULL CHECK (shortcode ~ '^[a-z0-9_]{2,32}$'),
    is_animated   BOOLEAN     NOT NULL DEFAULT false,
    position      INTEGER     NOT NULL CHECK (position >= 0),
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX custom_emoji_shortcode_key ON custom_emoji (pack_id, shortcode) WHERE deleted_at IS NULL;
CREATE INDEX custom_emoji_pack_idx ON custom_emoji (pack_id, position);
CREATE INDEX custom_emoji_attachment_idx ON custom_emoji (attachment_id);

CREATE TABLE user_emoji_packs (
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    pack_id    BIGINT      NOT NULL REFERENCES emoji_packs (id) ON DELETE CASCADE,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, pack_id)
);

CREATE INDEX user_emoji_packs_pack_idx ON user_emoji_packs (pack_id);

CREATE TABLE emoji_pack_reports (
    pack_id     BIGINT      NOT NULL REFERENCES emoji_packs (id) ON DELETE CASCADE,
    reporter_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reason      TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (pack_id, reporter_id)
);

CREATE INDEX emoji_pack_reports_reporter_idx ON emoji_pack_reports (reporter_id, created_at);

CREATE FUNCTION bump_emoji_pack_version() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    UPDATE emoji_packs SET version = version + 1 WHERE id = COALESCE(NEW.pack_id, OLD.pack_id);
    RETURN NULL;
END;
$$;

CREATE TRIGGER custom_emoji_bump_pack_version AFTER INSERT OR UPDATE OR DELETE ON custom_emoji
    FOR EACH ROW EXECUTE FUNCTION bump_emoji_pack_version();

